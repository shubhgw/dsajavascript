// O(1) is constant time complexity occured when the algorithm's execution time is constant and does not change with the input size ex; accessing an array element

// O(n) is linear time complexity occured when the algorithm's execution time increases linearly with the input size ex; accessign all array elements 

// O(n^2) is quadratic time complexity occured when the algorithm's execution time increases quadratically with the input size ex; loop inside a loop

// O(logn) is logarithmic time complexity occured when the algorithm's execution time increases logarithmically with the input size ex; binary search

// 2^n is exponential time complexity occured when the algorithm's execution time increases exponentially with the input size ex; recursive fibonacci  

// n! is is factorial time complexity occured when the time increases as n! with the input size 

// (n).log(n) is time complexity occured when the algorithm's execution time increases as n log(n) with the input size ex; merge sort, quick sort


